"""Offline narration with Kokoro (kokoro-onnx). No key, no cost.

python tts.py  ->  audio/vo/<id>.wav (hash-cached), out/vo.wav, timeline.json, out/captions.srt

The picture is timed to the voice: each line starts after the previous one, shots begin
at their first line, and shotMin stretches a shot whose footage needs longer than its lines.
"""
import hashlib
import json
import os
import sys

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL = os.environ.get("KOKORO_DIR", "/home/user/.cache/kokoro")
SR = 24000

cfg = json.load(open(os.path.join(HERE, "narration.json")))
os.makedirs(os.path.join(HERE, "audio/vo"), exist_ok=True)
os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
kokoro = None


def synth(line):
    key = hashlib.sha1(f"{cfg['voice']}|{cfg['speed']}|{line['say']}".encode()).hexdigest()[:12]
    path = os.path.join(HERE, "audio/vo", f"{line['id']}-{key}.wav")
    if not os.path.exists(path):
        global kokoro
        if kokoro is None:
            kokoro = Kokoro(os.path.join(MODEL, "kokoro-v1.0.onnx"), os.path.join(MODEL, "voices-v1.0.bin"))
        samples, sr = kokoro.create(line["say"], voice=cfg["voice"], speed=cfg["speed"], lang="en-us")
        sf.write(path, samples, sr)
        print(f"tts {line['id']}: {len(samples) / sr:.2f}s", file=sys.stderr)
    data, sr = sf.read(path, dtype="float32")
    assert sr == SR
    return data


t = cfg["preroll"]
shots, lines, prev_shot = {}, [], None
audio = {}
for line in cfg["lines"]:
    data = audio[line["id"]] = synth(line)
    if line["shot"] != prev_shot:
        if prev_shot is not None:
            t += cfg["shotGap"]
            start = shots[prev_shot]["from"]
            t = max(t, start + cfg["shotMin"].get(prev_shot, 0))
            shots[prev_shot]["to"] = t
        shots[line["shot"]] = {"from": t if prev_shot else 0.0}
        prev_shot = line["shot"]
    else:
        t += cfg["lineGap"]
    dur = len(data) / SR
    lines.append({"id": line["id"], "shot": line["shot"], "from": round(t, 3), "to": round(t + dur, 3), "caption": line["caption"]})
    t += dur
end = t + cfg["tail"]
end = max(end, shots[prev_shot]["from"] + cfg["shotMin"].get(prev_shot, 0))
shots[prev_shot]["to"] = end
for s in shots.values():
    s["from"], s["to"] = round(s["from"], 3), round(s["to"], 3)

vo = np.zeros(int(end * SR) + SR, dtype=np.float32)
for ln in lines:
    data = audio[ln["id"]]
    i = int(ln["from"] * SR)
    vo[i : i + len(data)] += data
sf.write(os.path.join(HERE, "out/vo.wav"), vo, SR)

timeline = {"dur": round(end, 3), "shots": shots, "lines": lines}
json.dump(timeline, open(os.path.join(HERE, "timeline.json"), "w"), indent=1)
with open(os.path.join(HERE, "timeline.js"), "w") as f:
    f.write("// generated by tts.py from narration.json: the picture is timed to the voice\nwindow.TIMELINE = " + json.dumps(timeline) + ";\n")


def ts(x):
    h, rem = divmod(x, 3600)
    m, s = divmod(rem, 60)
    return f"{int(h):02}:{int(m):02}:{int(s):02},{int(round((s % 1) * 1000)):03}"


with open(os.path.join(HERE, "out/captions.srt"), "w") as f:
    for i, ln in enumerate(lines, 1):
        f.write(f"{i}\n{ts(ln['from'])} --> {ts(ln['to'] + 0.25)}\n{ln['caption']}\n\n")
print(f"duration {end:.2f}s, {len(lines)} lines, shots: " + ", ".join(f"{k} {v['from']:.1f}-{v['to']:.1f}" for k, v in shots.items()))
